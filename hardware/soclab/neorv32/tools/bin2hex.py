#!/usr/bin/env python3
"""SPI flash image (.bin) -> $readmemh file for labs/lab3/sim/spi_flash_model.v.

    python tools/bin2hex.py build/ToneScale_sim10/ToneScale.bin [-o out.hex]

Same format as labs/lab3/script/bin2hex.py of the course repo: a few '//'
comment lines, then one byte per line (two lower-case hex digits), flash
address 0 first. Addresses past the end read as 0 in the model.
"""
import argparse
import hashlib
import sys
from pathlib import Path

MEM_BYTES = 65536   # MEM_BYTES of spi_flash_model.v


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("bin", type=Path)
    ap.add_argument("-o", "--output", type=Path, help="default: <bin>.hex")
    ap.add_argument("--mem-bytes", type=int, default=MEM_BYTES)
    args = ap.parse_args()

    data = args.bin.read_bytes()
    if not data:
        sys.exit(f"{args.bin}: empty image")
    if len(data) > args.mem_bytes:
        sys.exit(f"{args.bin}: {len(data)} bytes, more than the {args.mem_bytes} bytes of spi_flash_model.v")
    dst = args.output or args.bin.with_suffix(".hex")
    lines = [
        f"// {dst.name}: SPI flash image for labs/lab3/sim/spi_flash_model.v ($readmemh)",
        f"// from {args.bin.name}, {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}",
        "// generated by arduino/tools/bin2hex.py, do not edit. One byte per line,",
        "// flash address 0 first; addresses past the end read as 0.",
    ]
    lines += [f"{b:02x}" for b in data]
    with open(dst, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{args.bin.name} -> {dst} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
