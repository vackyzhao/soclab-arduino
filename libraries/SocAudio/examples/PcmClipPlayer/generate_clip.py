"""Regenerate the authored PCM asset; Python standard library only.

This produces an 80 ms rising electronic chirp, not a recording or WAV file.
Run: python generate_clip.py
"""

import math
from pathlib import Path

RATE = 48_000
COUNT = 3_840
PEAK = 6_000
START_HZ = 440.0
END_HZ = 880.0


def make_samples():
    duration = (COUNT - 1) / RATE
    chirp_rate = (END_HZ - START_HZ) / duration
    samples = []
    for index in range(COUNT):
        time = index / RATE
        phase = 2.0 * math.pi * (START_HZ * time + 0.5 * chirp_rate * time * time)
        envelope = math.sin(math.pi * index / (COUNT - 1)) ** 2
        samples.append(round(PEAK * envelope * math.sin(phase)))
    return samples


def main():
    samples = make_samples()
    rows = [", ".join(str(value) for value in samples[i : i + 12])
            for i in range(0, len(samples), 12)]
    header = """// Generated by generate_clip.py: authored 80 ms 440-to-880 Hz chirp.
// Mono signed int16_t PCM, 48000 samples/s. Not a recorded audio file.
#ifndef SOCLAB_EXAMPLE_CLIP_SAMPLES_H
#define SOCLAB_EXAMPLE_CLIP_SAMPLES_H
#include <stdint.h>

static const uint32_t CLIP_SAMPLE_RATE = 48000;
static const uint32_t CLIP_SAMPLE_COUNT = 3840;
static const int16_t clipSamples[CLIP_SAMPLE_COUNT] = {
"""
    header += "    " + ",\n    ".join(rows) + "\n};\n\n#endif\n"
    destination = Path(__file__).with_name("clip_samples.h")
    with destination.open("w", encoding="utf-8", newline="\n") as output:
        output.write(header)
    print(f"Wrote {destination.name}: {len(samples)} samples, "
          f"{len(samples) * 2} bytes, peak {max(abs(x) for x in samples)}")


if __name__ == "__main__":
    main()
